def fill_vars(template: str) -> str:
    pool = make_pool()
    result = template
    for key, val in pool.items():
        placeholder = "{" + key + "}"
        if placeholder in result:
            result = result.replace(placeholder, str(val))
    remaining = set(re.findall(r'\{(\w+)\}', result))
    for var in remaining:
        val = pool.get(var, f"[{var.replace('_', ' ')}]")
        result = result.replace("{" + var + "}", str(val))
    return result

