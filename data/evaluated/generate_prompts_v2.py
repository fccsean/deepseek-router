def make_prompt(idx: int) -> dict:
    domain = random.choice(list(TEMPLATES.keys()))
    domain_data = TEMPLATES[domain]

    # 复杂度分布 (pro倾斜: <=4: 38%, 5-7: 37%, 8-10: 25%)
    r = random.random()
    if r < 0.38:
        diff = random.choice(["easy", "easy", "medium"])
        complexity = random.randint(1, 4)
    elif r < 0.75:
        diff = random.choice(["medium", "medium", "hard"])
        complexity = random.randint(5, 7)
    else:
        diff = random.choice(["hard", "hard", "expert"])
        complexity = random.randint(8, 10)

    if diff not in domain_data:
        diffs = list(domain_data.keys())
        diff = random.choice(diffs)

    diff_data = domain_data[diff]
    ptype = random.choice(list(diff_data.keys()))
    templates = diff_data[ptype]
    template, tpl_complexity = random.choice(templates)
    complexity = max(1, min(10, int(complexity * 0.3 + tpl_complexity * 0.7)))

    prompt_text = fill_vars(template)

    # 加前缀
    prefix = random.choice(PREFIXES)

    # 加后缀（根据难度选不同后缀池）
    if complexity <= 3:
        suffix = random.choice(SUFFIXES_EASY)
    elif complexity <= 6:
        suffix = random.choice(SUFFIXES_MEDIUM)
    elif complexity <= 8:
        suffix = random.choice(SUFFIXES_HARD)
    else:
        suffix = random.choice(SUFFIXES_EXPERT)

    # 组装
    parts = [p for p in [prefix, prompt_text] if p]
    full_prompt = "\n".join(parts)
    full_prompt = full_prompt + "\n" + suffix if suffix else full_prompt

    if complexity <= 4:
        model = "deepseek-v4-flash"
        reason = "低复杂度，快速响应即可满足需求"
    elif complexity <= 7:
        model = "deepseek-v4-pro"
        reason = "中高复杂度，需要较强的推理能力"
    else:
        model = "deepseek-v4-pro"
        reason = "高复杂度，需要深度推理和多步思考链"

    if len(full_prompt) < 40:
        length_cat = "short"
    elif len(full_prompt) < 200:
        length_cat = "medium"
    else:
        length_cat = "long"

    return {
        "id": f"prompt_{idx:06d}",
        "prompt": full_prompt,
        "domain": domain,
        "difficulty": diff,
        "complexity_score": complexity,
        "length": length_cat,
        "recommended_model": model,
        "model_reason": reason,
        "type": ptype,
    }

def main():
    n = int(sys.argv[1]) if len(sys.argv) > 1 else 1000
    output = sys.argv[2] if len(sys.argv) > 2 else "prompts_100k.jsonl"

    with open(output, "w", encoding="utf-8") as f:
        for i in range(1, n + 1):
            p = make_prompt(i)
            f.write(json.dumps(p, ensure_ascii=False) + "\n")

    print(f"已生成 {n} 条prompt，保存至 {output}")

    prompts_set = set()
    flash = pro = 0
    domain_cnt = Counter()
    diff_cnt = Counter()
    with open(output, "r", encoding="utf-8") as f:
        for line in f:
            p = json.loads(line)
            prompts_set.add(p["prompt"])
            if p["recommended_model"] == "deepseek-v4-flash":
                flash += 1
            else:
                pro += 1
            domain_cnt[p["domain"]] += 1
            diff_cnt[p["difficulty"]] += 1

    print(f"\n唯一prompt: {len(prompts_set)} (重复率: {(1-len(prompts_set)/n)*100:.1f}%)")
    print(f"flash: {flash} ({flash/n*100:.1f}%)")
    print(f"pro:   {pro} ({pro/n*100:.1f}%)")
    print(f"\n领域分布:")
    for d, c in domain_cnt.most_common():
        print(f"  {d}: {c} ({c/n*100:.1f}%)")
    print(f"\n难度分布:")
    for d, c in sorted(diff_cnt.items()):
        print(f"  {d}: {c} ({c/n*100:.1f}%)")

if __name__ == "__main__":
    main()
